#!/usr/bin/env python3
"""Generate the RAM map (docs/en|ru/ram_map.md): every RAM / I/O-device address
that has a name or is accessed by the code, with the routines that read and
write it. Built from the 5269718 image (both images share the code).

Usage: python3 tools/gen_ram_docs.py --roms roms
"""
import argparse, bisect, collections, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

WORD_OPS = {"ldd", "std", "ldx", "stx", "ldy", "sty", "lds", "sts",
            "addd", "subd", "cpd", "cpx", "cpy"}
WRITE = ("st", "clr", "inc", "dec", "bset", "bclr", "com", "neg", "asl", "asr", "lsr", "rol", "ror")
REGIONS = [
    (0x0000, 0x00FF, ("Direct page RAM ($0000-$00FF)", "ОЗУ прямой страницы ($0000-$00FF)")),
    (0x0100, 0x03FF, ("Internal RAM above the direct page ($0100-$03FF)", "Внутреннее ОЗУ выше прямой страницы ($0100-$03FF)")),
    (0x0400, 0x0437, ("External I/O device registers ($0400-$0437)", "Регистры внешнего устройства ввода-вывода ($0400-$0437)")),
    (0x0438, 0x0FFF, ("External RAM ($0438 and up)", "Внешнее ОЗУ (от $0438)")),
]
T = {
    "en": dict(title="RAM map", intro=(
        "Generated by `tools/gen_ram_docs.py`; do not edit by hand. Names come from "
        "`annotations/ram_symbols.json` (names of the form `Lxxxx` are still unknown). **R** and **W** "
        "count the instructions that read and write the address (a 16-bit access counts for both "
        "bytes); the routine lists show up to five routines. Accesses through an index register (for example `ldx #$0135` then `brset 6,x`) are "
        "not counted, so a low count does not mean an address is unused."),
        cols="| Addr | Name | R | W | Read by | Written by |", unnamed="unnamed",
        summary="%d addresses listed, %d of them named, %d still with a placeholder name."),
    "ru": dict(title="Карта ОЗУ", intro=(
        "Генерируется `tools/gen_ram_docs.py`; не редактируйте вручную. Имена берутся из "
        "`annotations/ram_symbols.json` (имена вида `Lxxxx` пока неизвестны). **R** и **W** — число "
        "инструкций, которые читают и пишут адрес (16-битное обращение считается для обоих байтов); в "
        "списках показано до пяти подпрограмм. Обращения "
        "через индексный регистр (например, `ldx #$0135`, затем `brset 6,x`) не учитываются, так что "
        "малый счёт не значит, что адрес не используется."),
        cols="| Адрес | Имя | R | W | Читают | Пишут |", unnamed="без имени",
        summary="Всего адресов: %d, с именами: %d, с временным именем: %d."),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roms", default=os.path.join(ROOT, "roms"))
    args = ap.parse_args()
    from gen_source import Gen
    from fccdis import Rom
    g = Gen(Rom(os.path.join(args.roms, "5269718.bin")))
    g.analyse()
    ents = sorted(a for a, n in g.names.items()
                  if a in g.an.insn and not re.match(r'^L[0-9A-F]{4}$', n))
    rd = collections.defaultdict(collections.Counter)
    wr = collections.defaultdict(collections.Counter)
    for a, i in g.an.insn.items():
        for op in i.ops:
            if op[0] not in ("dir", "ext") or not (0 <= op[1] < 0x1000):
                continue
            k = ents[bisect.bisect_right(ents, a) - 1] if ents and a >= ents[0] else None
            r = g.names.get(k, "?")
            tgt = wr if i.mn.startswith(WRITE) else rd
            tgt[op[1]][r] += 1
            if i.mn in WORD_OPS:          # 16-bit access also touches the next byte
                tgt[op[1] + 1][r] += 1
    names = {a: n for a, n in g.ram.items() if a < 0x1000}
    addrs = sorted(set(names) | set(rd) | set(wr))
    for lang, t in T.items():
        L = 0 if lang == "en" else 1
        o = ["# " + t["title"], "", t["intro"], ""]
        named = sum(1 for a in addrs if a in names and not re.match(r'^L[0-9A-F]{4}$', names[a]))
        ph = sum(1 for a in addrs if a in names and re.match(r'^L[0-9A-F]{4}$', names[a]))
        o += [t["summary"] % (len(addrs), named, ph), ""]
        for lo, hi, title in REGIONS:
            rows = [a for a in addrs if lo <= a <= hi]
            if not rows:
                continue
            o += ["## " + title[L], "", t["cols"], "|---|---|---|---|---|---|"]
            for a in rows:
                n = names.get(a, "")
                n = "`%s`" % n if n else "*%s*" % t["unnamed"]
                r, w = rd.get(a, collections.Counter()), wr.get(a, collections.Counter())
                fmt = lambda c: ", ".join(sorted(c)[:5]) + (" …" if len(c) > 5 else "")
                o.append("| `$%04X` | %s | %d | %d | %s | %s |" % (
                    a, n, sum(r.values()), sum(w.values()), fmt(r), fmt(w)))
            o.append("")
        path = os.path.join(ROOT, "docs", lang, "ram_map.md")
        open(path, "w", encoding="utf-8").write("\n".join(o))
        print("wrote", path)


if __name__ == "__main__":
    main()
