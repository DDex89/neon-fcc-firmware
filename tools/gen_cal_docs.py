#!/usr/bin/env python3
"""Generate the calibration table reference and the variant comparison (docs/*/calibration_*.md).

    python tools/gen_cal_docs.py --roms roms/
"""
import argparse, bisect, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x1200


def load(name):
    with open(os.path.join(ROOT, "annotations", name), encoding="utf-8") as f:
        return json.load(f)


def clean(s):
    s = (s or "").strip()
    return "" if s.lower() in ("desc", "desc.", "description", "detailed description", "detailed_description") else s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roms", default=os.path.join(ROOT, "roms"))
    args = ap.parse_args()
    tables = {int(k, 16): v for k, v in load("tables.json").items()}
    variants = load("variants.json")
    starts = sorted(tables)
    groups = {}
    for a in starts:
        g = tables[a].get("group", "").replace("_", " ").replace("\\", " / ").strip(" /") or "Other"
        groups.setdefault(g, []).append(a)
    hdr = {
        "en": ("# Calibration table reference",
               "Generated by `tools/gen_cal_docs.py` from the table definitions (derived from the MP Tune "
               "definition files). Addresses are the same for every calibration built on code base B4CC. "
               "Descriptions are the original English ones; many are still placeholders.",
               ["Address", "Name", "Long name", "Type", "Description"]),
        "ru": ("# Справочник калибровочных таблиц",
               "Сгенерировано `tools/gen_cal_docs.py` из описаний таблиц (взятых из файлов определений MP Tune). "
               "Адреса одинаковы для всех калибровок на коде B4CC. Описания оставлены в оригинале на английском; "
               "многие из них пока заглушки.",
               ["Адрес", "Имя", "Полное имя", "Тип", "Описание"]),
    }
    for lang, (title, intro, cols) in hdr.items():
        out = [title, "", intro, ""]
        if lang == "en":
            out += ["Type codes: 0 = 2D point-slope curve, 2 = 2D curve (other format), 3 = byte constant, "
                    "4 = word constant, 5 = bit flags, 7 = 3D map (rows x cols), 9 = address list, "
                    "11 = O2 ramp kick table, 17 = 3D map with its own axis.", ""]
        else:
            out += ["Коды типов: 0 = 2D-кривая «точка-наклон», 2 = 2D-кривая (другой формат), 3 = байтовая константа, "
                    "4 = 16-битная константа, 5 = битовые флаги, 7 = 3D-карта (строки x столбцы), 9 = список адресов, "
                    "11 = таблица шагов лямбда-регулятора, 17 = 3D-карта со своей осью.", ""]
        for g in sorted(groups):
            out += ["## " + g, "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            for a in groups[g]:
                t = tables[a]
                out.append("| `$%04X` | `%s` | %s | %s | %s |" % (
                    a, t["cname"], t.get("lname", "").replace("_", " "), t.get("type", ""),
                    clean(t.get("desc", "")).replace("|", "/")))
            out.append("")
        path = os.path.join(ROOT, "docs", lang, "calibration_tables.md")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))
    # variant comparison
    roms = {}
    for pn in variants:
        p = os.path.join(args.roms, pn + ".bin")
        if os.path.exists(p):
            roms[pn] = open(p, "rb").read()
    if len(roms) < 2:
        print("variant comparison skipped (need two dumps)")
        return
    pa, pb = list(roms)[:2]
    a, b = roms[pa], roms[pb]
    diff = {}
    for addr in range(0xB800, 0xE229):
        if a[addr - BASE] != b[addr - BASE]:
            i = bisect.bisect_right(starts, addr) - 1
            key = starts[i] if i >= 0 else None
            diff.setdefault(key, 0)
            diff[key] += 1
    for lang in ("en", "ru"):
        if lang == "en":
            out = ["# Calibration differences: %s vs %s" % (pa, pb), "",
                   "%s: %s  " % (pa, variants[pa]["description"]), "%s: %s" % (pb, variants[pb]["description"]), "",
                   "Both use exactly the same program code; only the calibration area differs. "
                   "Tables listed below contain at least one different byte.", "",
                   "| Address | Table | Bytes changed | Description |", "|---|---|---|---|"]
        else:
            out = ["# Различия калибровок: %s и %s" % (pa, pb), "",
                   "%s: %s  " % (pa, variants[pa]["description"]), "%s: %s" % (pb, variants[pb]["description"]), "",
                   "Код программы у обеих прошивок одинаковый, отличается только область калибровок. "
                   "Ниже таблицы, в которых отличается хотя бы один байт.", "",
                   "| Адрес | Таблица | Изменено байт | Описание |", "|---|---|---|---|"]
        for k in sorted(x for x in diff if x is not None):
            t = tables[k]
            out.append("| `$%04X` | `%s` | %d | %s |" % (k, t["cname"], diff[k], clean(t.get("desc", "")) or t.get("lname", "").replace("_", " ")))
        out.append("")
        with open(os.path.join(ROOT, "docs", lang, "calibration_variants.md"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out))
    print("tables %d in %d groups; %d tables differ between %s and %s" % (len(tables), len(groups), len(diff), pa, pb))


if __name__ == "__main__":
    main()
